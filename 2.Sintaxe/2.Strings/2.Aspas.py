"""
    Strings: uma sequência de caracteres cercada por aspas simples ou duplas. 
"""

# Aspas simples
nome = 'João'
print(nome)

# Aspas duplas
nome = "João"
print(nome)

# Aspas triplas
nome = """João"""
print(nome)

# Aspas triplas com quebra de linha
nome = """João
Gomes
da Silva"""
print(nome)