"""
    Strings: uma sequência de caracteres cercada por aspas simples ou duplas. 
"""

# Aspas simples para escapar aspas duplas
msg = "it's working"
print(msg)

# Aspas duplas para escapar aspas simples
msg = 'She said "Hello"'
print(msg)

# Aspas simples para escapar aspas simples
msg = 'She said \'Hello\''
print(msg)

# Quando queremos usar aspas simples dentro de uma string, podemos usar aspas duplas para escapar as aspas simples.
msg = "She said \"Hello\""
print(msg)

